-- Phase 4 (P4-7): deposit reports in the report catalogue (US-113). Each is a function reporting.<name>(user, parameters)
-- returning plain rows limited to the branches the user may see, run and stored as CSV by the reporting module, and
-- schedulable like any other report (V19 gives each a job, off until scheduled).
--   1. DEPOSIT_BOOK: balances held, by branch and product, as at a day-end (from the movements, so any past date works).
--   2. DEPOSIT_MATURITY_PROFILE: term and recurring deposits by residual maturity (the time buckets of RBI's statement of
--      structural liquidity), and matured deposits not yet paid.
--   3. DEPOSIT_INTEREST_PAID: interest credited, recovered on early closure, paid out and taxed, by account, in a period.
--   4. DEPOSIT_TDS: every interest credit taxed in a period with the tax and its basis (the data for the quarterly TDS
--      return). No PAN is exported: the return is prepared from it with the PAN held encrypted (open item P4-24).
-- The depositor documents (statement, receipt, interest certificate) are generated by the application (P4-7).

-- ---------------------------------------------------------------------------------------------------------
-- Helpers
-- ---------------------------------------------------------------------------------------------------------
-- An account's balance at the end of a day: the sum of its movements up to and including that business date.
CREATE FUNCTION deposits.balance_as_at(p_account uuid, p_as_at date) RETURNS numeric LANGUAGE sql STABLE AS $$
  SELECT coalesce(sum(CASE m.direction WHEN 'CREDIT' THEN m.amount ELSE -m.amount END), 0)::numeric
    FROM deposits.movement m WHERE m.account_id = p_account AND m.business_date <= p_as_at
$$;

-- The time buckets of residual maturity, in order.
CREATE FUNCTION reporting.maturity_buckets() RETURNS TABLE (bucket text, sort_order int) LANGUAGE sql IMMUTABLE AS $$
  VALUES ('Matured, not paid', 0), ('1 day', 1), ('2 to 7 days', 2), ('8 to 14 days', 3), ('15 to 30 days', 4), ('31 days to 2 months', 5),
         ('Over 2 to 3 months', 6), ('Over 3 to 6 months', 7), ('Over 6 months to 1 year', 8), ('Over 1 to 3 years', 9),
         ('Over 3 to 5 years', 10), ('Over 5 years', 11)
$$;

CREATE FUNCTION reporting.maturity_bucket(p_as_at date, p_maturity date) RETURNS text LANGUAGE sql IMMUTABLE AS $$
  SELECT CASE WHEN p_maturity <= p_as_at THEN 'Matured, not paid'
              WHEN p_maturity - p_as_at = 1 THEN '1 day'
              WHEN p_maturity - p_as_at <= 7 THEN '2 to 7 days'
              WHEN p_maturity - p_as_at <= 14 THEN '8 to 14 days'
              WHEN p_maturity - p_as_at <= 30 THEN '15 to 30 days'
              WHEN p_maturity <= (p_as_at + interval '2 months')::date THEN '31 days to 2 months'
              WHEN p_maturity <= (p_as_at + interval '3 months')::date THEN 'Over 2 to 3 months'
              WHEN p_maturity <= (p_as_at + interval '6 months')::date THEN 'Over 3 to 6 months'
              WHEN p_maturity <= (p_as_at + interval '1 year')::date THEN 'Over 6 months to 1 year'
              WHEN p_maturity <= (p_as_at + interval '3 years')::date THEN 'Over 1 to 3 years'
              WHEN p_maturity <= (p_as_at + interval '5 years')::date THEN 'Over 3 to 5 years'
              ELSE 'Over 5 years' END
$$;

-- ---------------------------------------------------------------------------------------------------------
-- 1. Deposit book
-- ---------------------------------------------------------------------------------------------------------
CREATE FUNCTION reporting.rpt_deposit_book(p_user text, p_params jsonb)
RETURNS TABLE (as_at date, branch_code text, branch_name text, family text, product_code text, product_name text, product_type text,
               accounts bigint, balance numeric, average_balance numeric)
LANGUAGE sql STABLE AS $$
  WITH prm AS (SELECT least(reporting.param_date(p_params, 'asOf', reporting.business_date()), reporting.business_date()) AS d),
  bal AS (
    SELECT a.branch_code, a.family, a.product_code, deposits.balance_as_at(a.id, prm.d) AS balance
      FROM deposits.account a, prm
     WHERE a.branch_code IN (SELECT v.branch_code FROM platform.visible_branches(p_user) v))
  SELECT prm.d, bal.branch_code, b.name, bal.family, bal.product_code, p.name, p.product_type, count(*), sum(bal.balance),
         round(sum(bal.balance) / count(*), 2)
    FROM bal JOIN platform.branch b ON b.code = bal.branch_code JOIN deposits.product p ON p.code = bal.product_code, prm
   WHERE bal.balance <> 0
   GROUP BY prm.d, bal.branch_code, b.name, bal.family, bal.product_code, p.name, p.product_type
   ORDER BY bal.branch_code, bal.family, bal.product_code
$$;

-- ---------------------------------------------------------------------------------------------------------
-- 2. Maturity profile
-- ---------------------------------------------------------------------------------------------------------
CREATE FUNCTION reporting.rpt_deposit_maturity_profile(p_user text, p_params jsonb)
RETURNS TABLE (as_at date, branch_code text, branch_name text, bucket text, deposits bigint, principal numeric, balance numeric)
LANGUAGE sql STABLE AS $$
  WITH prm AS (SELECT least(reporting.param_date(p_params, 'asOf', reporting.business_date()), reporting.business_date()) AS d),
  pos AS (
    SELECT a.branch_code, t.principal::numeric AS principal, deposits.balance_as_at(a.id, prm.d) AS balance,
           reporting.maturity_bucket(prm.d, t.maturity_date) AS bucket
      FROM deposits.account a JOIN deposits.term_deposit t ON t.account_id = a.id, prm
     WHERE a.family = 'TERM_DEPOSIT' AND t.maturity_date IS NOT NULL AND t.start_date <= prm.d
       AND a.branch_code IN (SELECT v.branch_code FROM platform.visible_branches(p_user) v)),
  live AS (SELECT * FROM pos WHERE balance > 0)
  SELECT prm.d, br.branch_code, b.name, k.bucket, count(live.balance), coalesce(sum(live.principal), 0), coalesce(sum(live.balance), 0)
    FROM (SELECT DISTINCT branch_code FROM live) br
    JOIN platform.branch b ON b.code = br.branch_code
   CROSS JOIN reporting.maturity_buckets() k
    LEFT JOIN live ON live.branch_code = br.branch_code AND live.bucket = k.bucket, prm
   GROUP BY prm.d, br.branch_code, b.name, k.bucket, k.sort_order
   ORDER BY br.branch_code, k.sort_order
$$;

-- ---------------------------------------------------------------------------------------------------------
-- 3. Interest paid
-- ---------------------------------------------------------------------------------------------------------
CREATE FUNCTION reporting.rpt_deposit_interest_paid(p_user text, p_params jsonb)
RETURNS TABLE (from_date date, to_date date, branch_code text, account_no text, family text, product_code text, customer_no text,
               customer_name text, interest_credited numeric, interest_recovered numeric, net_interest numeric, tax_deducted numeric,
               interest_paid_out numeric)
LANGUAGE sql STABLE AS $$
  WITH prm AS (SELECT reporting.param_date(p_params, 'from', date_trunc('month', reporting.business_date())::date) AS f,
                      reporting.param_date(p_params, 'to', reporting.business_date()) AS t),
  mv AS (
    SELECT m.account_id,
           sum(m.amount) FILTER (WHERE m.kind = 'INTEREST_CREDIT') AS credited,
           sum(m.amount) FILTER (WHERE m.kind = 'INTEREST_RECOVERY') AS recovered,
           sum(m.amount) FILTER (WHERE m.kind = 'INTEREST_PAYOUT') AS paid_out
      FROM deposits.movement m, prm
     WHERE m.kind IN ('INTEREST_CREDIT','INTEREST_RECOVERY','INTEREST_PAYOUT') AND m.reversed_by IS NULL
       AND m.business_date BETWEEN prm.f AND prm.t
     GROUP BY m.account_id),
  tx AS (
    SELECT t.account_id, sum(t.tax) AS tax FROM deposits.tds_ledger t, prm WHERE t.business_date BETWEEN prm.f AND prm.t GROUP BY t.account_id)
  SELECT prm.f, prm.t, a.branch_code, a.account_no, a.family, a.product_code, c.customer_no, c.display_name,
         coalesce(mv.credited, 0)::numeric, coalesce(mv.recovered, 0)::numeric, (coalesce(mv.credited, 0) - coalesce(mv.recovered, 0))::numeric,
         coalesce(tx.tax, 0)::numeric, coalesce(mv.paid_out, 0)::numeric
    FROM mv FULL JOIN tx ON tx.account_id = mv.account_id
    JOIN deposits.account a ON a.id = coalesce(mv.account_id, tx.account_id)
    JOIN customer.customer c ON c.id = a.customer_id, prm
   WHERE a.branch_code IN (SELECT v.branch_code FROM platform.visible_branches(p_user) v)
   ORDER BY a.branch_code, a.account_no
$$;

-- ---------------------------------------------------------------------------------------------------------
-- 4. Tax deducted at source
-- ---------------------------------------------------------------------------------------------------------
CREATE FUNCTION reporting.rpt_deposit_tds(p_user text, p_params jsonb)
RETURNS TABLE (business_date date, tax_year text, quarter int, branch_code text, customer_no text, customer_name text, pan_on_file boolean,
               senior_citizen boolean, account_no text, interest numeric, tax numeric, rate_percent numeric, basis text,
               declaration_reference text)
LANGUAGE sql STABLE AS $$
  WITH prm AS (SELECT reporting.param_date(p_params, 'from', date_trunc('month', reporting.business_date())::date) AS f,
                      reporting.param_date(p_params, 'to', reporting.business_date()) AS t)
  SELECT t.business_date, t.tax_year || '-' || right((t.tax_year + 1)::text, 2), ((extract(month FROM t.business_date)::int + 8) % 12) / 3 + 1,
         a.branch_code, c.customer_no, c.display_name, t.pan_on_file, t.senior, a.account_no, t.interest::numeric, t.tax::numeric,
         t.rate_percent::numeric, t.basis, d.reference
    FROM deposits.tds_ledger t JOIN deposits.account a ON a.id = t.account_id JOIN customer.customer c ON c.id = t.customer_id
    LEFT JOIN deposits.tds_declaration d ON d.id = t.declaration_id, prm
   WHERE t.business_date BETWEEN prm.f AND prm.t
     AND a.branch_code IN (SELECT v.branch_code FROM platform.visible_branches(p_user) v)
   ORDER BY t.business_date, t.id
$$;

